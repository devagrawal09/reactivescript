//! Slice 2b (tier B) mechanisms: plain stores (slot nodes, the pending
//! backing and its fold, reconcile and adoption, a key held by an action),
//! optimistic memos over stores (`take`, kept guesses, a truth landing
//! beneath a guess), optimistic stores (per-row guesses, arrangement
//! guesses, presence, linked lanes) and derived optimistic stores (first
//! load, refresh, re-base, fold, a re-ask in another action's lane, a guess
//! standing in for its flight, a staged error), and the tracker demo.
//!
//! The op programs and their traces are in fixtures/slice2b-units.json; the
//! traces are Solid's (rc.21, regenerated by
//! docs/slice2b-fuzz/tools/unit-expectations.mjs from unit-programs.json).
use rust_solid::slice1::{JsObj, Key, Runtime, StoreKey, Value};
use serde_json::Value as J;
use std::{
    io::Write,
    process::{Command, Stdio},
    rc::Rc,
};

fn driver(ops: &J) -> J {
    let mut child = Command::new(env!("CARGO_BIN_EXE_slice1-driver"))
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .unwrap();
    writeln!(child.stdin.take().unwrap(), "{ops}").unwrap();
    let out = child.wait_with_output().unwrap();
    serde_json::from_slice(&out.stdout).unwrap()
}

fn unit(name: &str) {
    let all: J = serde_json::from_str(include_str!("fixtures/slice2b-units.json")).unwrap();
    let case = &all[name];
    assert!(case.is_object(), "{name} is a unit program");
    assert_eq!(driver(&case["ops"]), case["expected"], "{name}");
}

