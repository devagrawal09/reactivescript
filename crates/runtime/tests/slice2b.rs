/// A store proxy wraps one target: reads of the same raw row serve the
/// same proxy, and a setter's write is seen after it (store.ts `wrap`,
/// `storeSetter`; checked with the same calls on dist/prod).
#[test]
fn store_reads_and_writes_through_the_api() {
    let mut r = Runtime::default();
    let root = r.create_root();
    let row = Value::Obj(JsObj::new_object(vec![(Rc::from("a"), Value::Int(1))]));
    let list = Value::Obj(JsObj::new_array(vec![row]));
    let value = Value::Obj(JsObj::new_object(vec![(Rc::from("list"), list)]));
    let st = r.with_owner(Some(root), |r| r.create_store(value, false));
    let l1 = r.js_get(&st, &Key::name("list")).unwrap();
    let l2 = r.js_get(&st, &Key::name("list")).unwrap();
    assert!(matches!(l1, Value::Proxy(_)));
    assert_eq!(l1, l2);
    let row = r.js_get(&l1, &Key::Idx(0)).unwrap();
    assert_eq!(r.js_get(&row, &Key::name("a")).unwrap(), Value::Int(1));
    // A write outside the setter is ignored (the trap returns true).
    r.js_set(&row, &Key::name("a"), Value::Int(5)).unwrap();
    assert_eq!(r.js_get(&row, &Key::name("a")).unwrap(), Value::Int(1));
    r.store_set(&st, &mut |rt, d| {
        let list = rt.js_get(&d, &Key::name("list"))?;
        let row = rt.js_get(&list, &Key::Idx(0))?;
        rt.js_set(&row, &Key::name("a"), Value::Int(2))?;
        Ok(Value::Undef)
    })
    .unwrap();
    // A context-free read sees the committed backing until the flush.
    assert_eq!(r.js_get(&row, &Key::name("a")).unwrap(), Value::Int(1));
    r.flush();
    assert_eq!(r.js_get(&row, &Key::name("a")).unwrap(), Value::Int(2));
    // A positional reconcile keeps the row's proxy at the same index.
    let next = Value::Obj(JsObj::new_object(vec![(
        Rc::from("list"),
        Value::Obj(JsObj::new_array(vec![Value::Obj(JsObj::new_object(vec![
            (Rc::from("id"), Value::Undef),
            (Rc::from("a"), Value::Int(3)),
        ]))])),
    )]));
    r.store_reconcile(&st, next, StoreKey::Positional).unwrap();
    r.flush();
    let row2 = r.js_get(&l1, &Key::Idx(0)).unwrap();
    assert_eq!(row2, row);
    assert_eq!(r.js_get(&row2, &Key::name("a")).unwrap(), Value::Int(3));
}
