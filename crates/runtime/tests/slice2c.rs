//! its #2903 abort and retry, the small-move path and its duplicate
//! decline, index rows and index signals, the fallback, a shallow store's
//! view), owners with `onCleanup` lists and disposal, Show (its three memos,
//! function children, keyed), children built inside computations and their
//! parked frames (`parkChildren`, a staged pass's children dying on the
//! spot, zombies deferred, cancelled in a lane frame and re-run at commit,
//! `holdFrame`, `removalStagedBy`, the frame retired by the commit, a lane
//! seam or a lane dissolve, or dying with its owner), and the tracker demo
//! with Show + For.
//!
//! The op programs and their traces are in fixtures/slice2c-units.json; the
//! traces are Solid's (rc.21, regenerated by
//! docs/slice2c-fuzz/tools/unit-expectations.mjs from unit-programs.json).
use rust_solid::slice1::{Keyed, MapArg, Runtime, Value};
use serde_json::Value as J;
use std::{
    cell::RefCell,
    io::Write,
    process::{Command, Stdio},
    rc::Rc,
};

fn driver(ops: &J) -> J {
    let mut child = Command::new(env!("CARGO_BIN_EXE_slice1-driver"))
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .unwrap();
    writeln!(child.stdin.take().unwrap(), "{ops}").unwrap();
    let out = child.wait_with_output().unwrap();
    serde_json::from_slice(&out.stdout).unwrap()
}

fn unit(name: &str) {
    let all: J = serde_json::from_str(include_str!("fixtures/slice2c-units.json")).unwrap();
    let case = &all[name];
    assert!(case.is_object(), "{name} is a unit program");
    assert_eq!(driver(&case["ops"]), case["expected"], "{name}");
}

