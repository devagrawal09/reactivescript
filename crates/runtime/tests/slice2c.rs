/// `mapArray` on the API: an unchanged arrangement keeps the mapped
/// array's identity, a reorder reuses the rows, removals dispose them.
/// The same calls on Solid's dist/prod (`createRoot`, `createSignal([1,2])`,
/// `mapArray(() => xs(), x => (onCleanup(...), x * 10))`) give
/// `[10,20]`, the same array, `[20,10]`, `cleanup 1`, `[20]`, `cleanup 2`,
/// `[]`, with two mapper calls in all.
#[test]
fn map_array_api_identity_and_disposal() {
    let mut rt = Runtime::default();
    let root = rt.create_root();
    let log: Rc<RefCell<Vec<String>>> = Rc::default();
    let calls = Rc::new(RefCell::new(0));
    let xs = rt.with_owner(Some(root), |rt| {
        rt.signal_value(rust_solid::slice1::from_json(&serde_json::json!([1, 2])))
    });
    let (l2, c2) = (log.clone(), calls.clone());
    let m = rt.with_owner(Some(root), |rt| {
        rt.map_array(
            Rc::new(move |rt: &mut Runtime| rt.read_value(xs)),
            Rc::new(move |rt: &mut Runtime, item: MapArg, _: MapArg| {
                *c2.borrow_mut() += 1;
                let MapArg::Value(Value::Int(x)) = item else {
                    panic!("an identity row's item is the raw value")
                };
                let l3 = l2.clone();
                rt.on_cleanup(Box::new(move |_| {
                    l3.borrow_mut().push(format!("cleanup {x}"))
                }));
                Ok(Value::Int(x * 10))
            }),
            1,
            Keyed::Identity,
            None,
        )
    });
    let ints = |v: &Value| -> Vec<i64> {
        let Value::Obj(o) = v else { panic!() };
        o.elements().iter().map(|x| x.as_int().unwrap()).collect()
    };
    let set = |rt: &mut Runtime, v: serde_json::Value| {
        rt.write_value(xs, rust_solid::slice1::from_json(&v));
        rt.flush();
    };
    let a = rt.read_value(m).unwrap();
    assert_eq!(ints(&a), vec![10, 20]);
    set(&mut rt, serde_json::json!([1, 2]));
    let b = rt.read_value(m).unwrap();
    assert!(a == b, "no structural change keeps the mapped array");
    set(&mut rt, serde_json::json!([2, 1]));
    let c = rt.read_value(m).unwrap();
    assert_eq!(ints(&c), vec![20, 10]);
    assert!(b != c);
    set(&mut rt, serde_json::json!([2]));
    assert_eq!(ints(&rt.read_value(m).unwrap()), vec![20]);
    assert_eq!(*log.borrow(), vec!["cleanup 1"]);
    set(&mut rt, serde_json::json!([]));
    assert!(ints(&rt.read_value(m).unwrap()).is_empty());
    assert_eq!(*log.borrow(), vec!["cleanup 1", "cleanup 2"]);
    assert_eq!(*calls.borrow(), 2);
}
