// ---- in-memory modules under /p/src, with the brands package mapped as the ref runner maps it
const HEADER = "import type { Pure, Rejects, Ref, Instantiates, Server, Client } from \"@reactivescript/types\";\n";
function project(files) {
  const all = { "/p/node_modules/@reactivescript/types/index.d.ts": typesIndex };
  for (const [k, v] of Object.entries(files)) all[`/p/src/${k}`] = v;
  return all;
}
function gen(source, more = {}) {
  const files = project({ "m.ts": HEADER + source, ...more });
  return createDeclarations({ ts, read: f => files[f] }).record("/p/src/m");
}
const rows = r => r.text.split("\n").slice(1).filter(Boolean);
// the errors as `line:column message-fragment`; line numbers count the brand import above as line 1
const at = r => r.errors.map(e => `${e.line}:${e.column} ${e.code}`);

