test("records are memoized by their files' stamps and regenerate when one changes", { skip }, () => {
  const files = project({
    "m.ts": HEADER + 'export { f } from "./a";\nexport const k = 1;\n',
    "a.ts": HEADER + "export function f(): number { return 1; }\n",
  });
  const d = createDeclarations({ ts, read: f => files[f] });
  const first = d.record("/p/src/m");
  const t0 = performance.now();
  const second = d.record("/p/src/m");
  const hit = performance.now() - t0;
  assert.equal(second, first, "an unchanged module returns the memoized record");
  assert.ok(hit < 50, `a memo hit is fast (${hit.toFixed(1)}ms)`);
  files["/p/src/a.ts"] = HEADER + "export function f(): Pure<number> { return 1; }\n";
  const t1 = performance.now();
  const third = d.record("/p/src/m");
  const incremental = performance.now() - t1;
  assert.notEqual(third, first);
  assert.deepEqual(rows(third), ["export pure fn f(): number", "export const k: 1"]);
  assert.ok(incremental < 1000, `an edit regenerates incrementally (${incremental.toFixed(0)}ms)`);
  files["/p/src/m.ts"] = HEADER + 'export { f } from "./a";\n';
  assert.deepEqual(rows(d.record("/p/src/m")), ["export pure fn f(): number"]);
});

