#[test]
fn a_generated_declaration_binds_and_erases() {
    let main = "import { fetchUser, saveUser, NotFound, User, fields, createDebounced } from \"./api\"\nexport default component App() {\n  source q := \"a\"\n  user: User | null = await fetchUser(1) catch (e: NotFound) => null\n  slow = createDebounced(q, 100)\n  action save() { try { await saveUser({ id: 1 }) } catch (e) {} }\n  errored fallback(e) { <p>{e.message}</p> } { <p>{user == null ? slow : user.name}</p> }\n}\n";
    let rec = record("api.ts", GEN);
    assert_eq!(codes(&[("main.rx", main), ("api.ts", API_TS), ("rx-dts:api", &rec)]), Vec::<String>::new());
    // an io fn with no brand stays io
    let io = "import { saveUser } from \"./api\"\nexport default component App() {\n  x = saveUser(1)\n  <p>{x}</p>\n}\n";
    assert_eq!(codes(&[("main.rx", io), ("api.ts", API_TS), ("rx-dts:api", &rec)]), ["IO_IN_REACTIVE"]);
}

#[test]
fn the_import_narrows_only_a_defaulted_fact() {
    let rec = record("api.ts", GEN);
    let with = |main: &str| diags(&[("main.rx", main), ("api.ts", API_TS), ("rx-dts:api", &rec)]);
    let ok = "import pure { saveUser } from \"./api\"\nexport default component App() {\n  x = await saveUser(1)\n  errored fallback(e) { <p>{e.message}</p> } { <p>{x}</p> }\n}\n";
    assert_eq!(with(ok), vec![], "`import pure` narrows a defaulted io fact");
    let fails_default = "import { logVisit } from \"./api\" fails NotFound\nimport { NotFound } from \"./api\"\nexport default component App() {\n  action go() { try { await logVisit(\"x\") } catch (e: NotFound) {} }\n  <p>x</p>\n}\n";
    assert_eq!(with(fails_default), vec![], "`fails` narrows a defaulted rejection");
    let fails_brand = "import { fetchUser } from \"./api\" fails NotFound\nimport { NotFound } from \"./api\"\nexport default component App() { <p>x</p> }\n";
    assert_eq!(with(fails_brand), vec![("IMPORT_ROW_MISMATCH".into(), "MO-11e".into(), "main.rx".into(), 1)]);
    let side_brand = "import server { viewport } from \"./api\"\nexport default component App() { <p>x</p> }\n";
    assert_eq!(with(side_brand).into_iter().map(|d| d.0).collect::<Vec<_>>(), ["IMPORT_ROW_MISMATCH"]);
    let side_default = "import client { saveUser } from \"./api\"\nexport default component App() { <p>x</p> }\n";
    assert_eq!(with(side_default), vec![]);
    let missing = "import { deleteUser } from \"./api\"\nexport default component App() { <p>x</p> }\n";
    assert_eq!(with(missing), vec![("NOT_EXPORTED".into(), "MO-11b".into(), "main.rx".into(), 1)]);
}

#[test]
fn a_written_line_overrides_one_export() {
    let rec = record("api.ts", GEN);
    let written = "import { Card } from \"./cards\"\nexport fn fetchUser(id: number): Promise<User>\nexport fn deleteUser(id: number)\n";
    let main = "import pure { fetchUser } from \"./api\"\nexport default component App() { <p>x</p> }\n";
    let got = diags(&[("main.rx", main), ("api.ts", API_TS), ("api.d.rx", written), ("rx-dts:api", &rec), ("cards.d.rx", "export type Card = { id: number }\n")]);
    // deleteUser: a written line for a name the TS module lacks; fetchUser: written io, so `pure` cannot lower it
    assert!(got.contains(&("NOT_EXPORTED".into(), "MO-11e".into(), "api.d.rx".into(), 3)), "{got:?}");
    assert!(got.contains(&("IMPORT_ROW_MISMATCH".into(), "MO-11e".into(), "main.rx".into(), 1)), "{got:?}");
    // the generated lines W does not name stay
    let other = "import { saveUser } from \"./api\"\nexport default component App() { action a() { try { await saveUser(1) } catch (e) {} } <p>x</p> }\n";
    assert_eq!(codes(&[("main.rx", other), ("api.ts", API_TS), ("api.d.rx", "export fn fetchUser(id: number)\n"), ("rx-dts:api", &rec)]), Vec::<String>::new());
}

#[test]
fn no_generator_is_declaration_unavailable() {
    let main = "import { fetchUser } from \"./api\"\nexport default component App() { <p>x</p> }\n";
    let got = diags(&[("main.rx", main), ("api.ts", API_TS)]);
    assert_eq!(got, vec![("DECLARATION_UNAVAILABLE".into(), "MO-11d".into(), "main.rx".into(), 1)]);
    // a written declaration alone is MO-8's, unchanged
    assert_eq!(codes(&[("main.rx", main), ("api.ts", API_TS), ("api.d.rx", "export fn fetchUser(id: number)\n")]), Vec::<String>::new());
    // no TS module: no generator is asked, and the import is R-io-4's
    assert_eq!(codes(&[("main.rx", main), ("api.js", "export function fetchUser() {}")]), Vec::<String>::new());
}

#[test]
fn a_record_reports_its_errors_in_the_ts_module() {
    let main = "import { f } from \"./api\"\nexport default component App() { <p>x</p> }\n";
    let rec = json!({ "from": "api.ts", "text": "export fn f(n: number): number\n", "errors": [{ "file": "api.ts", "line": 2, "column": 20, "code": "DECLARATION_BRAND", "message": "misplaced" }], "files": ["api.ts"] }).to_string();
    assert_eq!(diags(&[("main.rx", main), ("api.ts", API_TS), ("rx-dts:api", &rec)]), vec![("DECLARATION_BRAND".into(), "MO-11c".into(), "api.ts".into(), 2)]);
    let cjs = json!({ "from": "api.ts", "text": "// generated\n", "errors": [{ "file": "api.ts", "line": 1, "column": 0, "code": "DECLARATION_UNAVAILABLE", "message": "export =" }], "files": ["api.ts"] }).to_string();
    let got = diags(&[("main.rx", main), ("api.ts", API_TS), ("rx-dts:api", &cjs)]);
    assert_eq!(got, vec![("DECLARATION_UNAVAILABLE".into(), "MO-11d".into(), "api.ts".into(), 1)]);
}

#[test]
fn a_type_import_in_a_declaration_reads_a_ts_module() {
    // MO-8e: `./cards` has no cards.d.rx and no cards.rx, but a TS module: its generated declaration
    let main = "import { show } from \"./api\"\nexport default component App() { <p>{show(1)}</p> }\n";
    let api = "import { Card, deal } from \"./cards\"\nexport pure fn show(c: Card): string\n";
    let rec = record("cards.ts", "export type Card\nexport fn deal(): Card\n");
    let got = diags(&[("main.rx", main), ("api.d.rx", api), ("cards.ts", "export type Card = {}\n"), ("rx-dts:cards", &rec)]);
    assert_eq!(got.into_iter().map(|d| (d.0, d.2)).collect::<Vec<_>>(), vec![("TYPE_IMPORT".to_string(), "api.d.rx".to_string())]);
    let none = diags(&[("main.rx", main), ("api.d.rx", api), ("cards.ts", "export type Card = {}\n")]);
    assert_eq!(none.into_iter().map(|d| (d.0, d.1)).collect::<Vec<_>>(), vec![("DECLARATION_UNAVAILABLE".to_string(), "MO-11d".to_string())]);
}

#[test]
fn the_model_and_the_projection_read_the_generated_lines() {
    let main = "import { fetchUser, saveUser, NotFound, User, createDebounced } from \"./api\"\nexport default component App() {\n  source q := \"a\"\n  user: User | null = await fetchUser(1) catch (e: NotFound) => null\n  slow = createDebounced(q, 100)\n  action save() { try { await saveUser({ id: 1 }) } catch (e) {} }\n  errored fallback(e) { <p>{e.message}</p> } { <p>{user == null ? slow : user.name}</p> }\n}\n";
    let rec = record("api.ts", GEN);
    let written = "export fn saveUser(u: User): Promise<void> rejects(Error)\n";
    let m: HashMap<String, String> = [("main.rx", main), ("api.ts", API_TS), ("api.d.rx", written), ("rx-dts:api", rec.as_str())].iter().map(|(k, v)| (k.to_string(), v.to_string())).collect();
    let read = |p: &str| m.get(p).cloned();
    let set = load_modules("main.rx", &read).unwrap();
    let checked = check_modules(&set, false);
    assert!(checked.diags.is_empty(), "{:?}", checked.diags);
    let syms = checked.models["main.rx"]["symbols"].as_array().unwrap().clone();
    let decl = |n: &str| syms.iter().find(|s| s["name"] == n).map(|s| s["decl"].clone()).unwrap();
    assert_eq!(decl("fetchUser"), json!({ "line": "export pure fn fetchUser(id: number): Promise<User> rejects(NotFound)", "from": "api.ts", "origin": "brand", "brands": ["Pure", "Rejects"] }));
    assert_eq!(decl("saveUser"), json!({ "line": "export fn saveUser(u: User): Promise<void> rejects(Error)", "from": "api.d.rx", "origin": "written", "brands": [] }));
    assert_eq!(decl("NotFound")["origin"], "default");
    assert_eq!(decl("createDebounced")["brands"], json!(["Pure", "Ref"]));
    let p = project_modules(&set);
    let code = &p.iter().find(|f| f.path == "main.rx.tsx").unwrap().code;
    assert!(code.contains("import type { User as __T___D_api_d_rx_User } from \"./api\";"), "{code}");
    assert!(code.contains("  export type User = __T___D_api_d_rx_User;"), "{code}");
    assert!(code.contains("const fetchUser = __js_fetchUser;"), "{code}");
    assert!(code.contains("import type { User } from \"./api\";"), "{code}");
    assert!(code.contains("const NotFound = __js_NotFound as unknown as __.Raise<typeof __js_NotFound>;"), "{code}");
    assert!(code.contains("const createDebounced = __js_createDebounced as unknown as (...a: __.ReadAt<Parameters<typeof __js_createDebounced>, 0>) => __.ReadResult<ReturnType<typeof __js_createDebounced>, \"ref\">;"), "{code}");
    assert!(!p.iter().any(|f| f.path == "api.d.ts"), "a generated declaration's module is the TS module");
}
