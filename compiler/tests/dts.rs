//! 09 MO-11: a TS module's declaration, generated (`rx-dts`) and read through the host's `read` at `rx-dts:<stem>` —
//! the parser's generated forms, the loader's merge with a written `.d.rx`, the checker's narrowing on a defaulted fact,
//! the model's `decl`, and the projection's TypeScript types (13 TY-4b, TY-4d). Records are written by hand here; the
//! generator itself is `compiler/dts.mjs` (`test/dts.mjs`), and `ref/crate.ts` diffs real records against `ref/`.

use reactivescript::check::check_modules;
use reactivescript::modules::load_modules;
use reactivescript::parse::{parse_declarations, parse_declarations_in, JsDecl};
use reactivescript::project::project_modules;
use serde_json::json;
use std::collections::HashMap;

fn record(from: &str, text: &str) -> String {
    json!({ "from": from, "text": text, "errors": [], "files": [from] }).to_string()
}
/// `(code, rule, file, line)` of each diagnostic of the program `main.rx` over `files`.
fn diags(files: &[(&str, &str)]) -> Vec<(String, String, String, i64)> {
    let m: HashMap<String, String> = files.iter().map(|(k, v)| (k.to_string(), v.to_string())).collect();
    let read = |p: &str| m.get(p).cloned();
    let set = load_modules("main.rx", &read).expect("loads");
    check_modules(&set, false).diags.into_iter().map(|d| (d.code, d.rule, d.file.unwrap_or_else(|| "main.rx".into()), d.line)).collect()
}
fn codes(files: &[(&str, &str)]) -> Vec<String> {
    diags(files).into_iter().map(|d| d.0).collect()
}

const API_TS: &str = "export function fetchUser(id: number) {}\n";
const GEN: &str = "// generated by rx-dts from ./api.ts\nexport error NotFound\nexport type User\nexport pure fn fetchUser(id: number): Promise<User> rejects(NotFound)\nexport fn saveUser(u: User): Promise<void>\nexport fn logVisit(page: string, ...tags: string[]): Promise<void>\nexport client fn viewport(): number\nexport const fields: readonly [\"name, first\", \"email\"]\nexport pure fn createDebounced(ref source: string, ms: number): ref string\nexport fn default(x: { a: string; b: (n: number) => void }): void\n";

#[test]
fn generated_forms_parse() {
    let ds = parse_declarations_in(GEN, true).unwrap();
    let names: Vec<&str> = ds.iter().map(|d| d.name()).collect();
    assert_eq!(names, ["NotFound", "User", "fetchUser", "saveUser", "logVisit", "viewport", "fields", "createDebounced", "default"]);
    match &ds[4] {
        JsDecl::Fn { params, ptypes, .. } => {
            assert_eq!(params, &["page", "...tags"]);
            assert_eq!(ptypes[1].as_deref(), Some("string[]"));
        }
        d => panic!("{d:?}"),
    }
    match &ds[6] {
        JsDecl::Const { ty, .. } => assert_eq!(ty.as_deref(), Some("readonly [\"name, first\", \"email\"]")),
        d => panic!("{d:?}"),
    }
    match &ds[8] {
        JsDecl::Fn { ptypes, .. } => assert_eq!(ptypes[0].as_deref(), Some("{ a: string; b: (n: number) => void }")),
        d => panic!("{d:?}"),
    }
    assert_eq!(ds[2].brands(), ["Pure", "Rejects"]);
    assert_eq!(ds[5].brands(), ["Client"]);
    assert_eq!(ds[7].brands(), ["Pure", "Ref"]);
    assert!(ds[3].brands().is_empty());
    assert_eq!(ds[2].src(), "export pure fn fetchUser(id: number): Promise<User> rejects(NotFound)");
}

#[test]
fn a_written_type_needs_a_body_and_const_is_a_value() {
    let e = parse_declarations("export type User\n").unwrap_err();
    assert!(e.0.contains("a type needs `= …`"), "{}", e.0);
    assert!(parse_declarations("export type User = { id: number }\nexport const limit: number\n").is_ok());
    let e = parse_declarations("export pure const limit: number\n").unwrap_err();
    assert!(e.0.contains("`export const` declares a value"), "{}", e.0);
    let e = parse_declarations("export fn f(ref ...xs: number[])\n").unwrap_err();
    assert!(e.0.contains("a rest parameter is a value parameter"), "{}", e.0);
}

